#!/bin/bash
# Issue #50 probe: two Hyperdrive configs to the wp-a2 PlanetScale database
# (global host and direct host), a probe Worker placed like wp-a2, then the
# latency and sql_mode tests. Read only on WordPress data; /session makes and
# drops one scratch table (a2probe_<time>).
#
#   CLOUDFLARE_API_TOKEN=...                      Hyperdrive edit, Workers Scripts edit
#   AWS_ACCESS_KEY_ID=... AWS_SECRET_ACCESS_KEY=...   the state bucket key
#   TF_VAR_mysql_user=... TF_VAR_mysql_password=... TF_VAR_mysql_database=...   as for wp-a2
#   ./tests/a2/probe.sh
#
# Options: PLACEMENT (default aws:us-east-2, as wp-a2), PLACEMENT_KEY (region,
# the default, or host: a single-homed host:port the Worker runs near, e.g.
# PLACEMENT_KEY=host PLACEMENT=aws-us-east-2.connect.psdb.cloud:3306), N (statements per
# latency run, default 50), RUNS (latency runs, default 3), SESSION_ONLY=1
# (skip the latency runs).
# Output: tests/a2/results/probe-<time>.json
set -euo pipefail
case "${PLACEMENT_KEY:-region}" in region|host) ;; *) echo "PLACEMENT_KEY must be region or host" >&2; exit 2 ;; esac
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
H="$ROOT/tests/a2"
TF="$H/terraform"
: "${CLOUDFLARE_API_TOKEN:?set CLOUDFLARE_API_TOKEN}"
umask 077
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
(cd "$TF" && terraform init -input=false >/dev/null && terraform apply -input=false -auto-approve >/dev/null)
ids=$(cd "$TF" && terraform output -json hyperdrive_ids)
G=$(printf '%s' "$ids" | python3 -c 'import json, sys; print(json.load(sys.stdin)["global"])')
D=$(printf '%s' "$ids" | python3 -c 'import json, sys; print(json.load(sys.stdin)["direct"])')
TOKEN=$(cd "$TF" && terraform output -raw probe_token)
export CLOUDFLARE_ACCOUNT_ID=${ACCOUNT_ID:-fabcb25d9c7eb087110ec474a03e50d2}
mkdir -p "$H/probe/gen"
cat > "$H/probe/gen/wrangler.toml" <<TOML
# Generated by tests/a2/probe.sh. Do not edit.
name = "wp-a2-probe"
main = "../worker.js"
compatibility_date = "2026-07-01"
compatibility_flags = ["nodejs_compat"]
workers_dev = true

[placement]
${PLACEMENT_KEY:-region} = "${PLACEMENT:-aws:us-east-2}"

[[hyperdrive]]
binding = "HD_GLOBAL"
id = "$G"

[[hyperdrive]]
binding = "HD_DIRECT"
id = "$D"
TOML
printf '{"PROBE_TOKEN": "%s"}' "$TOKEN" > "$W/secrets.json"
(cd "$H/probe" && [ -d node_modules ] || npm ci --silent)
DEP=$(cd "$H/probe/gen" && npx wrangler deploy --config wrangler.toml --secrets-file "$W/secrets.json" 2>&1) || { echo "$DEP" | tail -20; exit 1; }
rm -f "$W/secrets.json"
URL=$(echo "$DEP" | grep -oE 'https://[a-z0-9.-]+\.workers\.dev' | head -1)
echo "probe: $URL"
sleep 5
hdr() { printf 'header = "x-probe-token: %s"\n' "$TOKEN"; }
: > "$W/latency"
if [ "${SESSION_ONLY:-0}" != 1 ]; then
  for _ in $(seq 1 "${RUNS:-3}"); do
    curl -s -m 120 -K <(hdr) "$URL/latency?n=${N:-50}"; echo
  done > "$W/latency"
fi
curl -s -m 300 -K <(hdr) "$URL/session" > "$W/session"
mkdir -p "$H/results"
RES="$H/results/probe-$(date -u +%Y%m%dT%H%M%SZ).json"
python3 - "$W" "$RES" "${PLACEMENT_KEY:-region}=${PLACEMENT:-aws:us-east-2}" <<'PY'
import json, os, sys
w, res, placement = sys.argv[1:4]
lat = []
for l in [l for l in open(os.path.join(w, "latency")) if l.strip()]:
    try:
        lat.append(json.loads(l))
    except ValueError:
        lat.append({"error": l.strip()[:300]})
try:
    ses = json.load(open(os.path.join(w, "session")))
except ValueError:
    ses = {"error": open(os.path.join(w, "session")).read()[:300]}
json.dump({"placement": placement, "latency": lat, "session": ses}, open(res, "w"), indent=1)
for r in lat:
    for k, v in (r.get("latency") or {}).items():
        print("%-7s colo %s  connect %.1f ms  first %.1f ms  median %.2f ms  min %.2f  max %.2f  n %s %s" % (
            k, r.get("colo"), v.get("connect_ms") or -1, v.get("first_ms") or -1, v.get("median_ms") or -1,
            v.get("min_ms") or -1, v.get("max_ms") or -1, v.get("n"), v.get("error") or ""))
if ses.get("error"):
    print("SESSION ERROR:", ses["error"])
for k in ("server_session_mode", "server_global_mode", "server_version", "server_connection_id"):
    v = (ses.get("steps") or {}).get(k) or {}
    print("%-22s %s %s" % (k, v.get("shape") or ("ERROR %s" % v.get("errno") if v else "-"), v.get("rows") if v.get("shape") == "rows" else (v.get("error") or {kk: v.get(kk) for kk in ("affected", "info", "fieldCount")})))
print("relaxed mode tried:", ses.get("relaxed_mode"))
for k, v in (ses.get("verdict") or {}).items():
    print("%-40s %s" % (k, v))
def show(k, v):
    if isinstance(v, list):
        for i, x in enumerate(v):
            show("%s[%d]" % (k, i), x)
        return
    if isinstance(v, dict) and "sql" in v:
        print("  %-28s %-6s %s" % (k, "ran" if v.get("ok") else "ERR %s" % v.get("errno"), (v.get("error") or "")[:90]))
for k, v in (ses.get("steps") or {}).items():
    if not k.startswith("server_"):
        show(k, v)
print("scratch tables left:", ses.get("tables_left"))
print("result:", res)
PY
