#!/bin/bash
# Item 1 of issue #35, the real build: the b-dosql WordPress (PHP and its
# SQLite in one Durable Object, spikes/b2-wordpress) as a user Worker in the
# dispatch namespace, served through a site dispatcher, then measured.
#
#   CLOUDFLARE_API_TOKEN=... AWS_ACCESS_KEY_ID=... AWS_SECRET_ACCESS_KEY=... ./tests/wfp/dosql.sh
#
# Run tests/wfp/run.sh first (the namespace). Options: SITE (default wp-dosql;
# the script name in the namespace), PORT (local wrangler dev port for the
# OPcache step, default 8811), N (bench runs per page, default 10), BUILD=0
# (use the build that is there).
#
# The site dispatcher (<prefix>-site-<SITE>) sends every path to the one script
# (SITE_SCRIPT), as a platform does for one customer hostname. Output:
# tests/wfp/results/dosql-<time>.json, the same shape as deploy/results/.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
H="$ROOT/tests/wfp"
TF="$H/terraform"
APP="$ROOT/spikes/b2-wordpress"
: "${CLOUDFLARE_API_TOKEN:?set CLOUDFLARE_API_TOKEN}"
SITE=${SITE:-wp-dosql}
[[ "$SITE" =~ ^[a-z0-9-]{1,40}$ ]] || { echo "bad SITE" >&2; exit 2; }
export PORT=${PORT:-8811}
log() { printf '\n== %s\n' "$*"; }
umask 077
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
(cd "$TF" && terraform init -input=false >/dev/null && terraform apply -input=false -auto-approve >/dev/null)
out() { (cd "$TF" && terraform output -raw "$1"); }
ACCOUNT_ID=$(out account_id); NS=$(out namespace); PREFIX=$(out prefix)
export CLOUDFLARE_ACCOUNT_ID=$ACCOUNT_ID
SUB=$(curl -sf -K <(printf 'header = "Authorization: Bearer %s"\n' "$CLOUDFLARE_API_TOKEN") \
  "https://api.cloudflare.com/client/v4/accounts/$ACCOUNT_ID/workers/subdomain" \
  | python3 -c 'import json, sys; print(json.load(sys.stdin)["result"]["subdomain"])')

if [ "${BUILD:-1}" = 1 ]; then
  log "build b-dosql (PORT $PORT for the OPcache step)"
  cd "$APP"
  [ -d node_modules ] || npm ci --silent
  [ -f vendor/php_8_3.js ] || ./prepare.sh
  ./build.sh | tail -1
  DEV_ENV=dosql-local ./opcache.sh | tail -1
fi

# The user Worker config: deploy/deploy.sh's b-dosql config without
# workers_dev (a namespace script has no workers.dev name), no D1, no media.
CONF="$APP/wrangler.deploy.wfp-$SITE.toml"
COMPAT=$(sed -n 's/^compatibility_date = "\(.*\)"/\1/p' "$APP/wrangler.toml" | head -1)
cat > "$CONF" <<TOML
# Generated by tests/wfp/dosql.sh: b-dosql as a user Worker in namespace $NS.
name = "$SITE"
main = "index.js"
compatibility_date = "$COMPAT"
compatibility_flags = ["nodejs_compat"]
rules = [{ type = "Data", globs = ["**/*.zip"], fallthrough = false }]
[assets]
directory = "build/public"
[cache]
enabled = true
[vars]
PHP_ENV = '{"USE_ZEND_ALLOC":"0"}'
PHP_IN_DO = "on"
PHP_LOCATION = "enam"
PHP_DO_POOL = "1"
DB_IN_DO = "on"
[images]
binding = "IMAGES"
[[durable_objects.bindings]]
name = "PHP_RUNTIME"
class_name = "PhpRuntime"
[[migrations]]
tag = "v1"
new_sqlite_classes = ["PhpRuntime"]
TOML
(cd "$TF" && terraform output -json) | python3 -c '
import json, sys
o = {k: v["value"] for k, v in json.load(sys.stdin).items()}
json.dump({"WP_SALT": o["wp_salt"], "SPIKE_TOKEN": o["spike_token"]}, open(sys.argv[1], "w"))' "$W/secrets.json"

log "upload $SITE into $NS"
t0=$SECONDS
(cd "$APP" && npx wrangler deploy --config "$CONF" --dispatch-namespace "$NS" --secrets-file "$W/secrets.json") > "$W/upload.log" 2>&1 \
  || { tail -20 "$W/upload.log"; exit 1; }
rm -f "$W/secrets.json"
UPLOAD_S=$((SECONDS - t0))
grep -E 'Uploaded|Total Upload|Current Version' "$W/upload.log" || true

log "site dispatcher"
mkdir -p "$H/gen"
cat > "$H/gen/site-$SITE.toml" <<TOML
name = "$PREFIX-site-$SITE"
main = "../dispatcher/worker.js"
compatibility_date = "$COMPAT"
workers_dev = true

[vars]
SITE_SCRIPT = "$SITE"

[[dispatch_namespaces]]
binding = "DISPATCHER"
namespace = "$NS"

[[dispatch_namespaces]]
binding = "DISPATCHER_OUT"
namespace = "$NS"
outbound = { service = "$PREFIX-outbound", parameters = ["TENANT_FROM_DISPATCH"] }
TOML
(cd "$H/gen" && npx wrangler deploy --config "site-$SITE.toml") > "$W/site.log" 2>&1 || { tail -20 "$W/site.log"; exit 1; }
URL="https://$PREFIX-site-$SITE.$SUB.workers.dev"
echo "$URL"
SPIKE_TOKEN=$(out spike_token); ADMIN_PASSWORD=$(out admin_password)
# Headers with secrets go to curl in a config on a pipe, not in argv.
hdr() { printf 'header = "x-spike-token: %s"\n' "$SPIKE_TOKEN"; [ "${1:-}" != pw ] || printf 'header = "x-admin-password: %s"\n' "$ADMIN_PASSWORD"; }

log "install"
sleep 5
t0=$SECONDS
curl -s -m 300 -X POST -K <(hdr pw) "$URL/_install" > "$W/install.json" || true
INSTALL_S=$((SECONDS - t0))
python3 -c 'import json, sys
try:
    d = json.load(open(sys.argv[1])); print(d.get("out", "")[-80:], d.get("ms"), "ms")
except ValueError:
    print("install did not answer JSON:", open(sys.argv[1]).read()[:200])' "$W/install.json"

log "measure"
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
for i in 1 2 3; do curl -s -K <(hdr) "$URL/_dbping?db=object&n=200&nocache=$RANDOM$i"; echo; done > "$W/ping"
E2E_EXIT=0
SPIKE_TOKEN=$SPIKE_TOKEN ADMIN_PASSWORD=$ADMIN_PASSWORD "$APP/e2e.sh" "$URL" > "$W/e2e" 2>&1 || E2E_EXIT=$?
B=$URL ADMIN_PASSWORD=$ADMIN_PASSWORD N=${N:-10} python3 "$ROOT/tests/a/bench.py" > "$W/bench" 2>&1 || true
printf '{"namespace": "%s", "script": "%s", "upload_s": %s, "install_s": %s, "client": "%s"}\n' "$NS" "$SITE" "$UPLOAD_S" "$INSTALL_S" "${CLIENT:-laptop}" > "$W/extra"
mkdir -p "$H/results"
VARIANT=b-dosql python3 "$ROOT/deploy/summarize.py" "$H/results/dosql-$STAMP.json" "$SITE" "$URL" enam "$E2E_EXIT" "$W"
