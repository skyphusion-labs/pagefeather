// #328 PR 2: wranglerToml emitter for a b-dosql deploy/wfp user Worker.
// render_user in deploy/wfp/lib.sh is a thin call into this module (--toml).
// Fragments that still live in bash helpers (mail-from.mjs, http-allow.mjs,
// turnstile, obs, ...) arrive via render_user_parts. Derived resource names
// come from siteNames (#328 PR 1). Every golden must stay byte-identical.

import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { siteNames } from './wp-site-config.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '../..');
const LIB = join(ROOT, 'deploy/wfp/lib.sh');

export class WranglerTomlError extends Error {
  constructor(message, { exitCode = 1, stderr = '' } = {}) {
    super(message);
    this.exitCode = exitCode;
    this.stderr = stderr;
  }
}

// Collect fragments from lib.sh render_user_parts (same helpers, same refusals).
export function renderUserParts(site, origin, env = process.env) {
  const r = spawnSync(
    'bash',
    ['-c', '. "$1" >/dev/null; render_user_parts "$2" "$3"', 'x', LIB, site, origin],
    {
      cwd: ROOT,
      encoding: 'utf8',
      env: {
        PATH: env.PATH || process.env.PATH,
        HOME: env.HOME || process.env.HOME || '',
        ...env,
      },
    },
  );
  if (r.status !== 0) {
    throw new WranglerTomlError(r.stderr || `render_user_parts exit ${r.status}`, {
      exitCode: r.status == null ? 1 : r.status,
      stderr: r.stderr || '',
    });
  }
  try {
    return JSON.parse(r.stdout);
  } catch (e) {
    throw new WranglerTomlError(`render_user_parts: bad JSON: ${e.message}\n${r.stdout}`, {
      exitCode: 1,
      stderr: r.stderr || '',
    });
  }
}

// Assemble the TOML text. Shape matches the former render_user heredoc byte for byte.
// Bash $(...) strips trailing newlines from helper output, so $mail_vars / $ts_vars on their
// own heredoc lines get exactly one terminating newline from the heredoc line itself.
export function assembleWranglerToml(parts) {
  const names = siteNames(parts.site);
  if (parts.script && parts.script !== names.script) {
    throw new WranglerTomlError(`script drift: parts=${parts.script} siteNames=${names.script}`);
  }
  if (parts.media && parts.media !== names.mediaBucket) {
    throw new WranglerTomlError(`media drift: parts=${parts.media} siteNames=${names.mediaBucket}`);
  }
  const script = parts.script || names.script;
  const media = parts.media || names.mediaBucket;
  const phpLocation = parts.php_location || 'enam';
  const mailVars = parts.mail_vars || '';
  const tsVars = parts.ts_vars || '';

  let out = '';
  out += `# Generated by deploy/wfp for site ${parts.site} (b-dosql in namespace ${parts.namespace}). Do not edit.\n`;
  out += `name = "${script}"\n`;
  out += `main = "index.js"\n`;
  out += `compatibility_date = "${parts.compat}"\n`;
  out += `compatibility_flags = ["nodejs_compat", "enable_request_signal"]\n`;
  out += `rules = [{ type = "Data", globs = ["**/*.zip"], fallthrough = false }]\n`;
  out += `${parts.mail_binding}\n`;
  out += `[assets]\n`;
  out += `directory = "build/public"${parts.split_assets || ''}\n`;
  out += `[cache]\n`;
  out += `enabled = true\n`;
  out += `[exports.default]\n`;
  out += `type = "worker"\n`;
  out += `[exports.default.cache]\n`;
  out += `enabled = false\n`;
  out += `[exports.Pages]\n`;
  out += `type = "worker"\n`;
  out += `[exports.Pages.cache]\n`;
  out += `enabled = true\n`;
  out += `[vars]\n`;
  out += `PHP_ENV = '${parts.php_env}'\n`;
  out += `SITE_ORIGIN = "${parts.origin}"\n`;
  out += `SITE_NAME = "${parts.site}"\n`;
  out += `${mailVars}\n`;
  out += `HTTP_ALLOW_HOSTS = "${parts.http_allow}"\n`;
  out += `${tsVars}\n`;
  out += `PHP_IN_DO = "on"\n`;
  out += `PHP_LOCATION = "${phpLocation}"\n`;
  out += `PHP_DO_POOL = "1"\n`;
  out += `DB_IN_DO = "on"\n`;
  out += `[images]\n`;
  out += `binding = "IMAGES"\n`;
  out += `[[r2_buckets]]\n`;
  out += `binding = "MEDIA"\n`;
  out += `bucket_name = "${media}"\n`;
  out += `[[durable_objects.bindings]]\n`;
  out += `name = "PHP_RUNTIME"\n`;
  out += `class_name = "PhpRuntime"${parts.purge_suffix || ''}\n`;
  out += `[[migrations]]\n`;
  out += `tag = "v1"\n`;
  out += `new_sqlite_classes = ["PhpRuntime"]\n`;
  out += parts.obs || '';
  out += parts.search || '';
  out += parts.browser || '';
  return out;
}

export function wranglerToml({ site, origin, env = process.env } = {}) {
  if (!site || !origin) throw new WranglerTomlError('wranglerToml: site and origin are required');
  const parts = renderUserParts(site, origin, env);
  return assembleWranglerToml(parts);
}

function main(argv) {
  if (argv[2] !== '--toml' || !argv[3] || !argv[4]) {
    process.stderr.write('usage: wrangler-toml.mjs --toml <site> <origin>\n');
    process.exit(2);
  }
  try {
    process.stdout.write(wranglerToml({ site: argv[3], origin: argv[4], env: process.env }));
  } catch (e) {
    if (e instanceof WranglerTomlError) {
      if (e.stderr) process.stderr.write(e.stderr);
      else process.stderr.write(`${e.message}\n`);
      process.exit(e.exitCode || 1);
    }
    throw e;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv);
}
