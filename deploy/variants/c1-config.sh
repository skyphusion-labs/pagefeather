#!/bin/bash
# Print the Wrangler config for a c1 site (spikes/c1-woo-container) to stdout.
# deploy/variants/c1.sh writes it to spikes/c1-woo-container/wrangler.deploy.<name>.toml.
# All input comes from the environment; the values come from the Terraform outputs.
#
#   NAME           site name (the Worker; the container application is <NAME>-store)
#   PUBLIC_HOST    <NAME>.<subdomain>.workers.dev
#   REPLICA        replica bucket (Terraform output replica_bucket)
#   MEDIA_BUCKET   media bucket (Terraform output media_bucket)
#   R2_ENDPOINT    https://<account>.r2.cloudflarestorage.com (Terraform output r2_endpoint)
#   COMPAT         compatibility date
#   INSTANCE_TYPE  container instance type
#   PHP_WORKERS    PHP processes in the container
#   IDLE_SECONDS   the container stops after this many seconds with no request
#   OBJECT_CACHE   apcu (default) or none: the APCu object cache drop-in
#   QUEUE_RUNNER   local (default): WP-Cron and Action Scheduler run from the
#                  container every CRON_SECONDS (default 60); loopback: the
#                  Action Scheduler async loopback, as before (issue #45)
#   PAGE_CACHE_TTL seconds a storefront page stays fresh at the edge (default 120)
#   PAGE_CACHE_SWR seconds it may then be served stale while a new copy renders
#                  (default 600)
#   QUEUE_LIMIT    requests the container may have in hand before a page, cart or
#                  add to cart gets 503 (default 16; 0 = no limit; checkout,
#                  payment callbacks and admin are always let in; issue #39)
#   RETRY_AFTER    the Retry-After seconds of that 503 (default 5)
#   FLOW_LIMIT     the higher cap for a shopper already in a cart flow (a Cart-Token
#                  or a WooCommerce session; default 2 x QUEUE_LIMIT)
#   REPLICA_PATH   path of the Litestream replica in the replica bucket (default
#                  store). Another path restores and writes another database;
#                  going back to store finds the old one unchanged.
#   SEED_SHA256    optional (deploy/import.sh, issue #31): with no replica at
#                  REPLICA_PATH, the container loads <REPLICA_PATH>.seed.sqlite
#                  from the replica bucket, which must have this SHA-256
#
# No account id: Wrangler reads CLOUDFLARE_ACCOUNT_ID.
set -euo pipefail
OBJECT_CACHE=${OBJECT_CACHE:-apcu}
REPLICA_PATH=${REPLICA_PATH:-store}
PAGE_CACHE_TTL=${PAGE_CACHE_TTL:-120}
PAGE_CACHE_SWR=${PAGE_CACHE_SWR:-600}
QUEUE_LIMIT=${QUEUE_LIMIT:-16}
RETRY_AFTER=${RETRY_AFTER:-5}
FLOW_LIMIT=${FLOW_LIMIT:-}
QUEUE_RUNNER=${QUEUE_RUNNER:-local}
CRON_SECONDS=${CRON_SECONDS:-60}
for v in NAME PUBLIC_HOST REPLICA MEDIA_BUCKET R2_ENDPOINT COMPAT INSTANCE_TYPE PHP_WORKERS IDLE_SECONDS; do
  [ -n "${!v:-}" ] || { echo "c1-config.sh: $v is empty" >&2; exit 1; }
done
# Every value goes into a TOML string. Refuse anything that is not a plain
# name, so no value can break out of its string.
chk() { [[ "$2" =~ $3 ]] || { echo "c1-config.sh: $1 is not valid: $2" >&2; exit 1; }; }
chk NAME "$NAME" '^[a-z0-9][a-z0-9-]{0,62}$'
chk PUBLIC_HOST "$PUBLIC_HOST" '^[a-z0-9.-]+$'
chk REPLICA "$REPLICA" '^[a-z0-9][a-z0-9-]{1,62}$'
chk MEDIA_BUCKET "$MEDIA_BUCKET" '^[a-z0-9][a-z0-9-]{1,62}$'
chk R2_ENDPOINT "$R2_ENDPOINT" '^https://[a-f0-9]{32}\.r2\.cloudflarestorage\.com$'
chk COMPAT "$COMPAT" '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
chk INSTANCE_TYPE "$INSTANCE_TYPE" '^[a-z0-9-]+$'
chk PHP_WORKERS "$PHP_WORKERS" '^[1-9][0-9]?$'
chk IDLE_SECONDS "$IDLE_SECONDS" '^[1-9][0-9]*$'
chk OBJECT_CACHE "$OBJECT_CACHE" '^(none|apcu)$'
chk REPLICA_PATH "$REPLICA_PATH" '^[a-z0-9][a-z0-9-]{0,62}$'
chk QUEUE_RUNNER "$QUEUE_RUNNER" '^(local|loopback)$'
chk CRON_SECONDS "$CRON_SECONDS" '^[1-9][0-9]{0,3}$'
chk PAGE_CACHE_TTL "$PAGE_CACHE_TTL" '^[1-9][0-9]{0,4}$'
chk PAGE_CACHE_SWR "$PAGE_CACHE_SWR" '^[0-9]{1,5}$'
chk QUEUE_LIMIT "$QUEUE_LIMIT" '^[0-9]{1,4}$'
chk RETRY_AFTER "$RETRY_AFTER" '^[1-9][0-9]{0,3}$'
# The default needs a checked QUEUE_LIMIT.
[ -n "$FLOW_LIMIT" ] || FLOW_LIMIT=$((2 * QUEUE_LIMIT))
chk FLOW_LIMIT "$FLOW_LIMIT" '^[0-9]{1,4}$'
[ "$FLOW_LIMIT" -ge "$QUEUE_LIMIT" ] || { echo "c1-config.sh: FLOW_LIMIT ($FLOW_LIMIT) is below QUEUE_LIMIT ($QUEUE_LIMIT)" >&2; exit 1; }
SEED_SHA256=${SEED_SHA256:-}
[ -z "$SEED_SHA256" ] || chk SEED_SHA256 "$SEED_SHA256" '^[a-f0-9]{64}$'
cat <<TOML
# Generated by deploy/deploy.sh for $NAME (variant c1). Do not edit: run deploy.sh again.
name = "$NAME"
main = "worker.js"
compatibility_date = "$COMPAT"
workers_dev = true

[assets]
directory = "build/public"

# Workers Caching for the Storefront entrypoint only (worker.js, issue #58).
# The default entrypoint is the gateway: it decides by cookie name and path,
# and is not cached. Needs Wrangler 4.107.0 or later.
[exports.default]
type = "worker"

  [exports.default.cache]
  enabled = false

[exports.Storefront]
type = "worker"

  [exports.Storefront.cache]
  enabled = true

[vars]
PUBLIC_HOST = "$PUBLIC_HOST"
REPLICA_BUCKET = "$REPLICA"
REPLICA_PATH = "$REPLICA_PATH"
PHP_WORKERS = "$PHP_WORKERS"
IDLE_SECONDS = "$IDLE_SECONDS"
OBJECT_CACHE = "$OBJECT_CACHE"
QUEUE_RUNNER = "$QUEUE_RUNNER"
CRON_SECONDS = "$CRON_SECONDS"
PAGE_CACHE_TTL = "$PAGE_CACHE_TTL"
PAGE_CACHE_SWR = "$PAGE_CACHE_SWR"
QUEUE_LIMIT = "$QUEUE_LIMIT"
RETRY_AFTER = "$RETRY_AFTER"
FLOW_LIMIT = "$FLOW_LIMIT"
R2_ENDPOINT = "$R2_ENDPOINT"
SEED_SHA256 = "$SEED_SHA256"
# Secrets (deploy --secrets-file): WP_SALT, ADMIN_PASSWORD, SPIKE_TOKEN,
# LITESTREAM_ACCESS_KEY_ID, LITESTREAM_SECRET_ACCESS_KEY

[[r2_buckets]]
binding = "MEDIA"
bucket_name = "$MEDIA_BUCKET"

[images]
binding = "IMAGES"

# The Worker version id: /_store-info compares the Store object's version with it.
[version_metadata]
binding = "CF_VERSION_METADATA"

[[containers]]
name = "$NAME-store"
class_name = "Store"
image = "./container/Dockerfile"
image_build_context = "."
instance_type = "$INSTANCE_TYPE"
max_instances = 1
rollout_step_percentage = 100

[[durable_objects.bindings]]
name = "STORE"
class_name = "Store"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["Store"]
TOML
